#This ia a Baby ChatGPT!Predicts words based on the training

#RNN is a supervised learning 
#generating text based short text
#import libraries 
#objective of code : Is to generate text based on short text input
import numpy as np #used for scientific computing 
import tensorflow as tf #
from tensorflow.keras.models import Sequential#used to stack data in sequential manner
from tensorflow.keras.layers import Dense,LSTM,Embedding 
#keras is a API for solving ml problems
#layers :
# Dense :Just your regular densely-connected NN layer.
#LSTM :varient of RNN 
#embedding :Turns positive integers (indexes) into dense vectors of fixed size.
from tensorflow.keras.utils import to_categorical # converts integers into binary class matrix
from tensorflow.keras.preprocessing.text import Tokenizer 
#tokenizer : divides text into tokens or small units 
#diff bet tokens and tensors 
#step 1: prepare dataset  
text="Mumbai's Diwali fireworks are a vibrant display of light and sound, celebrated with great enthusiasm and festive spirit. However, the city has implemented strict rules to manage the firecracker usage, especially during the festival."

#step 2 :Tokenization 
#tokenization is the process of dividing the text into tokens or units to process 
tokens=Tokenizer() 
tokens.fit_on_texts([text]) #fit_on_text is used to produce outputs like one-hot encoding(eg.,hey:1,i:2,...)
#**tokens.fit_on_texts() only takes list of texts not a single text becoz of this we are using [] brackets


#step 3: extract vocabulary size and convert into sequences 
vocab_size=len(tokens.word_index) + 1 #word_index is used to create vocabulary index depending on frequency of word
sequences=[] #used to create list of sequences 

#step 4: nested for loop for creating the sequences 
for line in text.split(','):
    encoded=tokens.texts_to_sequences([line])[0] # text_to_sequences is used for converting text into numerial sequences starting from index 0
    for i in range(1,len(encoded)): 
        sequence=encoded[:i + 1] #
        sequences.append(sequence) #creating a nested for loop


#step 5:find the maximum sequence length for padding 
#padding :to add some token for short sequences so they have same length 
if sequences:
    max_sequence_len = max(len(seq) for seq in sequences)
else:
    raise ValueError("The 'sequences' variable is empty. Check the input data or preprocessing steps.")

#print(sequences)
#step 6:pad the sequences and prepare input-output pairs 
sequences=np.array(tf.keras.preprocessing.sequence.pad_sequences(sequences,maxlen=max_sequence_len)) #creating new sequences in which each word of text is of same length depending on the highest word length in the text.
x,y=sequences[:,:-1],sequences[:,-1]  #here -1 is for not adding the last column becoz last column is the output column which model do not show eg., if the text size is 3 then last column 3 is output column which is generated by model(remember that it starts from 0)  
y= to_categorical(y,num_classes=vocab_size) #it converts the vector class to binary matrix 

#step 7:build the RNN model 
#sequential(model):a plain stack of layers where each layer has exactly one input tensor and one output tensor 
#core embeddig layer:its a type of class.turn non negative ints to dense vactors of fixed size.
#input shape is 2d and output shape is 3d tensor 

model=Sequential([#sequential model 
    Embedding(input_dim=vocab_size,output_dim=10,input_length=x.shape[1]),
    LSTM(50), #LSTM layer has 50 units 
    Dense(vocab_size,activation='softmax') #dense is regularly densely connected neural network 

    ])
#step 8:model training 
#configures the model for training 
model.compile(loss='categorical_crossentropy',optimizer='adam',metrics=['accuracy'])
#adam :adaptive moment estimation ,adjust the learning rate for faster to improve the training speed 
#categorical crossentropy :its a loss function 
 
model.fit(x,y,epochs=250,verbose=2)
#epochs :single pass of model or iterations 
#verbose :a flag level of output generated during the run of a program  

#step 9:text generation(for user) :
#here text_to_sequences is just to convert input input text to output so to train the model

def generate_text(seedtext,nextword,max_sequence_len):
    #this function is to generate actual text,this function requaires input parameters
    #like the 1st word i.e.,seed text,next words(numbers or words genertaed after seed word),max_sequence_len is is the number of words(want in output).
    for _ in range(nextword): # _ means blank spaces holder becoz we do need any variable here to store any value simply i want to iterate. this loop will iterate from 0 to nextword
        token_list=tokens.texts_to_sequences([seedtext])[0] #converts input text to numerical sequences .removes the outer list basically
        token_list=tf.keras.preprocessing.sequence.pad_sequences([token_list],maxlen=max_sequence_len - 1,padding='pre')#Pads sequences to the same length. pre-padding or removing values from sequences from begining is default
        predicted=np.argmax(model.predict(token_list,verbose=0),axis=1) #verbose can be 0,1 or 2 .it is just for giving the info about data or past data ,if verbose is 0
        #we are using the trained model to make predictions based on token_list.
        #predicted word is used to store the indices using argmax() where argmax means, 
        #predict() generates output predictions for the input samples
        #returns the indices of the maximum values

#ML part ends here(training part ends) 


        #python part starts(testing part starts) :
        for word,index in tokens.word_index.items(): 
            #in this we are just finding the corresponding word to predicted index by our model.
            #tokens.word_index.items() means more frequent words are assigned lower index values,eg.,if the word is 'the' then it is assigned with lower index value and if word is 'recognize' then it is assigned with high index value.
            #a method to retrieve the dictionary's key value pair for iterations 

            if index == predicted :
                seedtext += " "+word #if the predicted word index exists (our library) in my index (found) then make seed_text.
                #simply add to word building a text step by step like a baby crawl steps 
                break 
    return seedtext 

print(generate_text("This Festival",25,max_sequence_len))    














